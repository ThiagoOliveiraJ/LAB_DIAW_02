CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login      VARCHAR(60)  NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    nome       VARCHAR(150) NOT NULL
);

CREATE TABLE cliente (
    id        BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    rg        VARCHAR(20)  NOT NULL UNIQUE,
    cpf       VARCHAR(11)  NOT NULL UNIQUE,
    endereco  VARCHAR(255) NOT NULL,
    profissao VARCHAR(100) NOT NULL
);

CREATE TABLE rendimento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id           BIGINT         NOT NULL REFERENCES cliente (id) ON DELETE CASCADE,
    entidade_empregadora VARCHAR(150)   NOT NULL,
    valor                NUMERIC(12, 2) NOT NULL CHECK (valor > 0)
);

CREATE INDEX idx_rendimento_cliente ON rendimento (cliente_id);

CREATE TABLE agente (
    id   BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('EMPRESA', 'BANCO')),
    cnpj VARCHAR(14) NOT NULL UNIQUE
);

CREATE TABLE automovel (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula      VARCHAR(30) NOT NULL UNIQUE,
    ano            INTEGER     NOT NULL,
    marca          VARCHAR(60) NOT NULL,
    modelo         VARCHAR(60) NOT NULL,
    placa          VARCHAR(7)  NOT NULL UNIQUE,
    proprietario_id BIGINT     NOT NULL REFERENCES usuario (id)
);

CREATE TABLE parecer_financeiro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agente_id     BIGINT       NOT NULL REFERENCES agente (id),
    resultado     VARCHAR(10)  NOT NULL CHECK (resultado IN ('POSITIVO', 'NEGATIVO')),
    justificativa VARCHAR(500) NOT NULL,
    emitido_em    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE pedido_aluguel (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao       BIGINT      NOT NULL,
    cliente_id   BIGINT      NOT NULL REFERENCES cliente (id),
    automovel_id BIGINT      NOT NULL REFERENCES automovel (id),
    parecer_id   BIGINT UNIQUE REFERENCES parecer_financeiro (id),
    data_inicio  DATE        NOT NULL,
    data_fim     DATE        NOT NULL,
    observacoes  VARCHAR(500),
    status       VARCHAR(15) NOT NULL
        CHECK (status IN ('EM_ANALISE', 'APROVADO', 'REPROVADO', 'CANCELADO', 'CONTRATADO')),
    criado_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (data_fim >= data_inicio)
);

CREATE INDEX idx_pedido_cliente ON pedido_aluguel (cliente_id);
CREATE INDEX idx_pedido_automovel ON pedido_aluguel (automovel_id);

CREATE TABLE contrato_credito (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    banco_id           BIGINT         NOT NULL REFERENCES agente (id),
    valor              NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    taxa_juros_mensal  NUMERIC(5, 2)  NOT NULL CHECK (taxa_juros_mensal >= 0),
    parcelas           INTEGER        NOT NULL CHECK (parcelas > 0)
);

CREATE TABLE contrato (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id   BIGINT         NOT NULL UNIQUE REFERENCES pedido_aluguel (id),
    agente_id   BIGINT         NOT NULL REFERENCES agente (id),
    credito_id  BIGINT UNIQUE REFERENCES contrato_credito (id),
    tipo        VARCHAR(10)    NOT NULL CHECK (tipo IN ('CLIENTE', 'EMPRESA', 'BANCO')),
    valor_total NUMERIC(12, 2) NOT NULL CHECK (valor_total > 0),
    assinado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
